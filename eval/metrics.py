#!/usr/bin/env python3
"""Compute held-out detection metrics and bootstrap confidence intervals."""

from __future__ import annotations

import argparse
import csv
import hashlib
import math
import random
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Dict, List, Optional, Sequence, Tuple

try:
    from .common import load_labels, sample_candidates
except ImportError:
    from common import load_labels, sample_candidates

DEFAULT_THRESHOLDS = (50, 70, 90)
METRIC_FIELDS = (
    "scope",
    "dataset",
    "threshold",
    "selected_from_calibration",
    "evaluated_apps",
    "true_positive",
    "false_positive",
    "true_negative",
    "false_negative",
    "precision",
    "recall",
    "f1",
    "f1_bootstrap_mean",
    "f1_ci_low",
    "f1_ci_high",
    "f1_ci_margin",
)


@dataclass(frozen=True)
class ScoredExample:
    score: int
    label: int
    sample_id: str
    variant_type: str


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="Compute held-out iRE-Zero precision, recall, F1, and bootstrap confidence intervals."
    )
    parser.add_argument("results_csv", type=Path, help="CSV generated by eval/run_corpus.py")
    parser.add_argument("labels_csv", type=Path, help="Ground-truth CSV used for the corpus run")
    parser.add_argument("--output", type=Path, default=Path("eval/metrics.csv"), help="Metric CSV path")
    parser.add_argument(
        "--thresholds",
        type=int,
        nargs="+",
        default=list(DEFAULT_THRESHOLDS),
        help="Scores at or above these thresholds are predicted positive",
    )
    parser.add_argument(
        "--split",
        type=float,
        default=0.0,
        help="Held-out fraction in (0,1); selection uses calibration rows and metrics use held-out rows only.",
    )
    parser.add_argument("--seed", type=int, default=1337, help="Stable split and bootstrap seed")
    parser.add_argument("--bootstrap", type=int, default=1000, help="Bootstrap resample count for F1 intervals")
    return parser


def main(argv: Optional[Sequence[str]] = None) -> int:
    args = build_parser().parse_args(argv)
    if args.split < 0 or args.split >= 1:
        print("--split must be at least 0 and less than 1", file=sys.stderr)
        return 2
    try:
        examples = read_labeled_examples(args.results_csv.resolve(), args.labels_csv.resolve())
    except (OSError, ValueError) as exc:
        print(f"Unable to compute metrics: {exc}", file=sys.stderr)
        return 2
    if not examples:
        print("Unable to compute metrics: no successfully analyzed labeled rows found", file=sys.stderr)
        return 2
    calibration, evaluation = split_examples(examples, args.split, args.seed)
    selected_threshold = select_threshold(calibration, args.thresholds)
    rows = evaluate_scopes(
        evaluation,
        args.thresholds,
        selected_threshold,
        args.bootstrap,
        args.seed,
        "held_out" if args.split else "all",
    )
    output = args.output.resolve()
    output.parent.mkdir(parents=True, exist_ok=True)
    with output.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=METRIC_FIELDS)
        writer.writeheader()
        writer.writerows(rows)
    print(
        f"Calibration: {len(calibration)} app(s); held-out evaluation: {len(evaluation)} app(s); "
        f"selected threshold: {selected_threshold}"
    )
    print(format_metrics([row for row in rows if row["scope"] == "all"]))
    print(f"[metrics] {output}")
    return 0


def read_labeled_examples(results_path: Path, labels_path: Path) -> List[ScoredExample]:
    labels = load_labels(labels_path)
    examples: List[ScoredExample] = []
    with results_path.open("r", encoding="utf-8", newline="") as handle:
        reader = csv.DictReader(handle)
        required = {"ipa_file", "score", "status"}
        missing = required - set(reader.fieldnames or [])
        if missing:
            raise ValueError(f"results.csv missing column(s): {', '.join(sorted(missing))}")
        for row_number, row in enumerate(reader, start=2):
            if str(row.get("status", "")).strip().lower() != "ok":
                continue
            match = labels.match(
                sample_candidates(
                    sha256=str(row.get("sha256", "")),
                    relative_path=str(row.get("ipa_relative_path", "")),
                    filename=str(row.get("ipa_file", "")),
                    bundle_identifier=str(row.get("bundle_identifier", "")),
                )
            )
            if match is None:
                raise ValueError(f"successful result row {row_number} has no matching label")
            try:
                score = int(str(row.get("score", "")).strip())
            except ValueError as exc:
                raise ValueError(f"result row {row_number} has invalid score") from exc
            filename = str(row.get("ipa_file", ""))
            variant_type = str(row.get("variant_type", "")).strip() or (
                "subtle" if "__irez.subtle" in filename else "obvious" if match.label == 1 else "real_benign"
            )
            sample_id = str(row.get("sha256", "")).strip() or filename
            examples.append(ScoredExample(score, match.label, sample_id, variant_type))
    return examples


def read_labeled_scores(results_path: Path, labels_path: Path) -> List[Tuple[int, int]]:
    return [(example.score, example.label) for example in read_labeled_examples(results_path, labels_path)]


def split_examples(
    examples: List[ScoredExample],
    held_out_fraction: float,
    seed: int,
) -> Tuple[List[ScoredExample], List[ScoredExample]]:
    if held_out_fraction <= 0:
        return examples, examples
    strata: Dict[str, List[ScoredExample]] = {}
    for example in examples:
        stratum = example.variant_type if example.label else "real_benign"
        strata.setdefault(stratum, []).append(example)
    calibration: List[ScoredExample] = []
    held_out: List[ScoredExample] = []
    for stratum, items in sorted(strata.items()):
        ordered = sorted(items, key=lambda item: _stable_order(item.sample_id, seed, stratum))
        count = min(len(items) - 1, max(1, math.ceil(len(items) * held_out_fraction))) if len(items) > 1 else 1
        held_out.extend(ordered[:count])
        calibration.extend(ordered[count:])
    if not calibration:
        calibration = list(examples)
    return calibration, held_out


def select_threshold(examples: List[ScoredExample], thresholds: Sequence[int]) -> int:
    scored = [(float(compute_metrics([(item.score, item.label) for item in examples], threshold)["f1"]), threshold) for threshold in thresholds]
    return max(scored, key=lambda pair: (pair[0], pair[1]))[1]


def evaluate_scopes(
    examples: List[ScoredExample],
    thresholds: Sequence[int],
    selected_threshold: int,
    bootstrap_iterations: int,
    seed: int,
    dataset: str = "held_out",
) -> List[Dict[str, str]]:
    scopes = {
        "all": examples,
        "obvious": [item for item in examples if item.label == 0 or item.variant_type == "obvious"],
        "subtle": [item for item in examples if item.label == 0 or item.variant_type == "subtle"],
    }
    rows: List[Dict[str, str]] = []
    for scope, scoped in scopes.items():
        if not scoped or not any(item.label == 1 for item in scoped):
            continue
        for threshold in thresholds:
            row = compute_metrics([(item.score, item.label) for item in scoped], threshold)
            mean, low, high = bootstrap_f1(scoped, threshold, bootstrap_iterations, seed + threshold + len(scope))
            row.update(
                {
                    "scope": scope,
                    "dataset": dataset,
                    "selected_from_calibration": "true" if threshold == selected_threshold else "false",
                    "f1_bootstrap_mean": f"{mean:.4f}",
                    "f1_ci_low": f"{low:.4f}",
                    "f1_ci_high": f"{high:.4f}",
                    "f1_ci_margin": f"{(high - low) / 2:.4f}",
                }
            )
            rows.append(row)
    return rows


def compute_metrics(examples: List[Tuple[int, int]], threshold: int) -> Dict[str, str]:
    tp = sum(1 for score, label in examples if score >= threshold and label == 1)
    fp = sum(1 for score, label in examples if score >= threshold and label == 0)
    tn = sum(1 for score, label in examples if score < threshold and label == 0)
    fn = sum(1 for score, label in examples if score < threshold and label == 1)
    precision = _ratio(tp, tp + fp)
    recall = _ratio(tp, tp + fn)
    f1 = _ratio(2 * precision * recall, precision + recall)
    return {
        "threshold": str(threshold),
        "evaluated_apps": str(len(examples)),
        "true_positive": str(tp),
        "false_positive": str(fp),
        "true_negative": str(tn),
        "false_negative": str(fn),
        "precision": f"{precision:.4f}",
        "recall": f"{recall:.4f}",
        "f1": f"{f1:.4f}",
    }


def bootstrap_f1(
    examples: List[ScoredExample],
    threshold: int,
    iterations: int = 1000,
    seed: int = 1337,
) -> Tuple[float, float, float]:
    if not examples or iterations <= 0:
        value = float(compute_metrics([(item.score, item.label) for item in examples], threshold)["f1"])
        return value, value, value
    rng = random.Random(seed)
    values: List[float] = []
    for _ in range(iterations):
        sample = rng.choices(examples, k=len(examples))
        values.append(float(compute_metrics([(item.score, item.label) for item in sample], threshold)["f1"]))
    values.sort()
    mean = sum(values) / len(values)
    return mean, _percentile(values, 0.025), _percentile(values, 0.975)


def format_metrics(rows: List[Dict[str, str]]) -> str:
    lines = ["threshold  apps  TP  FP  TN  FN  precision  recall  F1      95% CI"]
    for row in rows:
        selected = "*" if row.get("selected_from_calibration") == "true" else " "
        lines.append(
            f"{selected}{row['threshold']:>8}  {row['evaluated_apps']:>4}  "
            f"{row['true_positive']:>2}  {row['false_positive']:>2}  "
            f"{row['true_negative']:>2}  {row['false_negative']:>2}  "
            f"{row['precision']:>9}  {row['recall']:>6}  {row['f1']:>6}  "
            f"[{row['f1_ci_low']}, {row['f1_ci_high']}]"
        )
    return "\n".join(lines)


def _stable_order(value: str, seed: int, stratum: str) -> str:
    return hashlib.sha256(f"{seed}:{stratum}:{value}".encode("utf-8")).hexdigest()


def _percentile(values: List[float], quantile: float) -> float:
    index = min(len(values) - 1, max(0, round((len(values) - 1) * quantile)))
    return values[index]


def _ratio(numerator: float, denominator: float) -> float:
    return numerator / denominator if denominator else 0.0


if __name__ == "__main__":
    raise SystemExit(main())
